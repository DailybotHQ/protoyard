/** Standard SQL with the common Postgres and SQLite spellings. */
export const sqlGrammar: Grammar = {
  name: 'sql',
  start: 'code',
  states: {
    code: [
      WHITESPACE,
      { re: sticky(String.raw`--[^\n]*`), kind: 'comment' },
      BLOCK_COMMENT,
      // '' escapes a quote; strings may span lines.
      { re: sticky(String.raw`'(?:[^']|'')*(?:'|(?![\s\S]))`), kind: 'string' },
      {
        re: sticky(String.raw`"(?:[^"]|"")*(?:"|(?![\s\S]))|\x60[^\x60\n]*\x60?`),
        kind: 'property',
      },
      { re: sticky(String.raw`\$\d+|[:@][A-Za-z_]\w*|\?`), kind: 'variable' },
      { re: sticky(String.raw`[A-Za-z_]\w*`), kind: word },
      C_NUMBER,
      { re: sticky(String.raw`[<>=!|+\-*/%]+`), kind: 'operator' },
      { re: sticky('[(),;.]'), kind: 'punctuation' },
    ],
  },
};
