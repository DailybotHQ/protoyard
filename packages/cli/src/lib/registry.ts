/**
 * `.protoyard/registry.json` is the compact metadata index the gallery and
 * `list` read. It is regenerated by `protoyard index`; an incremental cache
 * keyed by manifest path + mtime + size avoids re-parsing unchanged files.
 */

export const REGISTRY_FORMAT = 'protoyard.registry';
export const REGISTRY_VERSION = 1;
/** v3: catalog blueprints (`blueprints/*.json`, kind `blueprint`) are indexed. */
const CACHE_VERSION = 3;

/** The manifest's catalog block as indexed: `shell` resolved for card framing. */
export interface RegistryCatalog {
  category: Catalog['category'];
  productType: string | null;
  platforms: Catalog['platforms'];
  /** `catalog.shell`, else `preview.shell`, with `auto` resolved from the platform. */
  shell: ResolvedShell;
  features: string[];
  highlights: string[];
  difficulty: Catalog['difficulty'] | null;
}

export interface RegistryEntry {
  kind: FolderKind;
  id: string;
  slug: string;
  name: string;
  description: string;
  version: string;
  category: string;
  tags: string[];
  platform: PrototypeManifest['platform'];
  status: PrototypeManifest['status'];
  template: string | null;
  icon: string | null;
  thumbnail: string | null;
  scenarios: string[];
  scenarioCount: number;
  defaultScenario: string | null;
  defaultTheme: string;
  defaultMode: PrototypeManifest['defaultMode'];
  viewport: PrototypeManifest['preview']['viewport'];
  namespace: string;
  schemaVersion: number;
  /** Workspace-relative folder, e.g. `prototypes/crm-demo`. */
  path: string;
  /** Manifest file mtime (ISO) — the "last modified" sort key. */
  modifiedAt: string;
  createdAt: string | null;
  updatedAt: string | null;
  /** Marketplace metadata, or null when the manifest has no catalog block. */
  catalog: RegistryCatalog | null;
}

export interface RegistryIssue {
  path: string;
  errors: string[];
}

export interface Registry {
  format: typeof REGISTRY_FORMAT;
  version: typeof REGISTRY_VERSION;
  generatedAt: string;
  entries: RegistryEntry[];
  invalid: RegistryIssue[];
  stats: {
    total: number;
    prototypes: number;
    templates: number;
    blueprints: number;
    invalid: number;
  };
}

interface CacheRecord {
  mtimeMs: number;
  size: number;
  entry: RegistryEntry | null;
  errors: string[];
}

interface IndexCache {
  version: typeof CACHE_VERSION;
  records: Record<string, CacheRecord>;
}

export interface IndexResult {
  registry: Registry;
  /** How many manifests were parsed vs served from cache. */
  parsed: number;
  cached: number;
  durationMs: number;
}

export function toRegistryEntry(
  manifest: PrototypeManifest,
  location: ManifestLocation,
  mtimeMs: number
): RegistryEntry {
  return {
    kind: location.folderKind,
    id: manifest.id,
    slug: manifest.slug,
    name: manifest.name,
    description: manifest.description,
    version: manifest.version,
    category: manifest.category,
    tags: manifest.tags,
    platform: manifest.platform,
    status: manifest.status,
    template: manifest.template ?? null,
    icon: manifest.icon ?? null,
    thumbnail: manifest.thumbnail ?? null,
    scenarios: manifest.scenarios,
    scenarioCount: manifest.scenarios.length,
    defaultScenario: manifest.defaultScenario ?? null,
    defaultTheme: manifest.defaultTheme,
    defaultMode: manifest.defaultMode,
    viewport: manifest.preview.viewport,
    namespace: manifest.storage.namespace,
    schemaVersion: manifest.storage.schemaVersion,
    path: location.relDir,
    modifiedAt: new Date(mtimeMs).toISOString(),
    createdAt: manifest.createdAt ?? null,
    updatedAt: manifest.updatedAt ?? null,
    catalog: toRegistryCatalog(manifest),
  };
}

function toRegistryCatalog(manifest: PrototypeManifest): RegistryCatalog | null {
  const catalog = manifest.catalog;
  if (!catalog) return null;
  return {
    category: catalog.category,
    productType: catalog.productType ?? null,
    platforms: catalog.platforms,
    shell: resolveShell(catalog.shell ?? manifest.preview.shell, manifest.platform),
    features: catalog.features,
    highlights: catalog.highlights,
    difficulty: catalog.difficulty ?? null,
  };
}

function catalogFromBlueprint(blueprint: Blueprint): RegistryCatalog | null {
  const catalog = blueprint.catalog;
  if (!catalog) return null;
  return {
    category: catalog.category,
    productType: catalog.productType ?? null,
    platforms: catalog.platforms,
    shell: resolveShell(catalog.shell ?? 'auto', 'responsive'),
    features: catalog.features,
    highlights: catalog.highlights,
    difficulty: catalog.difficulty ?? null,
  };
}

/** Registry row for a data-only catalog blueprint under `blueprints/<slug>.json`. */
export function toBlueprintRegistryEntry(
  blueprint: Blueprint,
  location: ManifestLocation,
  id: string,
  slug: string,
  mtimeMs: number
): RegistryEntry {
  const catalog = catalogFromBlueprint(blueprint);
  return {
    kind: 'blueprint',
    id,
    slug,
    name: blueprint.name,
    description: blueprint.description ?? '',
    version: '0.1.0',
    category: blueprint.category ?? catalog?.category ?? 'general',
    tags: blueprint.tags,
    platform: 'responsive',
    status: 'ready',
    template: 'crud-app',
    icon: blueprint.icon ?? null,
    thumbnail: null,
    scenarios: [],
    scenarioCount: 0,
    defaultScenario: null,
    defaultTheme: catalogBlueprintThemeId(blueprint),
    defaultMode: 'system',
    viewport: 'desktop',
    namespace: `blueprint-${slug}`,
    schemaVersion: 1,
    path: location.relDir,
    modifiedAt: new Date(mtimeMs).toISOString(),
    createdAt: null,
    updatedAt: null,
    catalog,
  };
}

async function readCache(path: string): Promise<IndexCache> {
  try {
    const cache = JSON.parse(await readFile(path, 'utf8')) as IndexCache;
    if (cache.version === CACHE_VERSION && cache.records && typeof cache.records === 'object') {
      return cache;
    }
  } catch {
    // A missing or corrupt cache only costs a cold index.
  }
  return { version: CACHE_VERSION, records: {} };
}

/** Writes via a temp file + rename so a reader never sees half a registry. */
export async function writeJsonAtomic(path: string, value: unknown): Promise<void> {
  await mkdir(dirname(path), { recursive: true });
  const temp = `${path}.${process.pid}.tmp`;
  await writeFile(temp, `${JSON.stringify(value, null, 2)}\n`, 'utf8');
  await rename(temp, path);
}

export async function buildIndex(
  paths: WorkspacePaths,
  options: { useCache?: boolean; write?: boolean; now?: () => Date } = {}
): Promise<IndexResult> {
  const started = performance.now();
  const useCache = options.useCache ?? true;
  const cache: IndexCache = useCache
    ? await readCache(paths.indexCache)
    : { version: CACHE_VERSION, records: {} };
  const nextCache: IndexCache = { version: CACHE_VERSION, records: {} };
  const locations = await listManifestLocations(paths);

  let parsed = 0;
  let cached = 0;
  const entries: RegistryEntry[] = [];
  const invalid: RegistryIssue[] = [];

  // Stat in parallel (cheap), parse only what changed.
  const stats = await Promise.all(locations.map((l) => statManifest(l)));
  await Promise.all(
    locations.map(async (location, i) => {
      const fileStat = stats[i] ?? null;
      const key = location.relDir;
      const hit = cache.records[key];
      let record: CacheRecord;
      if (hit && fileStat && hit.mtimeMs === fileStat.mtimeMs && hit.size === fileStat.size) {
        record = hit;
        cached++;
      } else if (location.folderKind === 'blueprint') {
        const result = await readBlueprintCatalog(location, fileStat);
        parsed++;
        record = {
          mtimeMs: fileStat?.mtimeMs ?? 0,
          size: fileStat?.size ?? 0,
          entry:
            result.blueprint && result.id && result.slug
              ? toBlueprintRegistryEntry(
                  result.blueprint,
                  location,
                  result.id,
                  result.slug,
                  fileStat?.mtimeMs ?? 0
                )
              : null,
          errors: result.errors,
        };
      } else {
        const result = await readManifest(location, fileStat);
        parsed++;
        record = {
          mtimeMs: fileStat?.mtimeMs ?? 0,
          size: fileStat?.size ?? 0,
          entry: result.manifest
            ? toRegistryEntry(result.manifest, location, fileStat?.mtimeMs ?? 0)
            : null,
          errors: result.errors,
        };
      }
      // Missing manifests are not cached: they have no mtime to key on.
      if (fileStat) nextCache.records[key] = record;
      if (record.entry) entries.push(record.entry);
      else invalid.push({ path: key, errors: record.errors });
    })
  );

  // Ids must be unique across the workspace: two prototypes sharing one id
  // would also share browser storage expectations and snapshot targets.
  const byId = new Map<string, RegistryEntry[]>();
  for (const entry of entries) byId.set(entry.id, [...(byId.get(entry.id) ?? []), entry]);
  const duplicates = new Set<RegistryEntry>();
  for (const [id, group] of byId) {
    if (group.length < 2) continue;
    for (const entry of group) {
      duplicates.add(entry);
      invalid.push({
        path: entry.path,
        errors: [
          `id "${id}" is also used by ${group
            .filter((e) => e !== entry)
            .map((e) => e.path)
            .join(', ')}.`,
        ],
      });
    }
  }
  const unique = entries.filter((e) => !duplicates.has(e));
  unique.sort(compareEntries);
  invalid.sort((a, b) => a.path.localeCompare(b.path));

  const registry: Registry = {
    format: REGISTRY_FORMAT,
    version: REGISTRY_VERSION,
    generatedAt: (options.now?.() ?? new Date()).toISOString(),
    entries: unique,
    invalid,
    stats: {
      total: unique.length,
      prototypes: unique.filter((e) => e.kind === 'prototype').length,
      templates: unique.filter((e) => e.kind === 'template').length,
      blueprints: unique.filter((e) => e.kind === 'blueprint').length,
      invalid: invalid.length,
    },
  };

  if (options.write ?? true) {
    await writeJsonAtomic(paths.registry, registry);
    await writeJsonAtomic(paths.indexCache, nextCache);
  }
  return { registry, parsed, cached, durationMs: performance.now() - started };
}

const KIND_ORDER: Record<FolderKind, number> = {
  prototype: 0,
  blueprint: 1,
  template: 2,
};

/** Default order: prototypes, then blueprints, then templates; then name, then slug. */
export function compareEntries(a: RegistryEntry, b: RegistryEntry): number {
  if (a.kind !== b.kind) return KIND_ORDER[a.kind] - KIND_ORDER[b.kind];
  return a.name.localeCompare(b.name) || a.slug.localeCompare(b.slug);
}

export async function readRegistry(paths: WorkspacePaths): Promise<Registry | null> {
  try {
    const registry = JSON.parse(await readFile(paths.registry, 'utf8')) as Registry;
    if (registry.format !== REGISTRY_FORMAT || registry.version !== REGISTRY_VERSION) return null;
    return registry;
  } catch {
    return null;
  }
}

/**
 * Returns a fresh registry: incremental re-index is cheap (stat only for
 * unchanged manifests), so commands never act on a stale list.
 */
export async function loadRegistry(paths: WorkspacePaths): Promise<Registry> {
  return (await buildIndex(paths)).registry;
}

export interface RegistryQuery {
  kind?: FolderKind | 'all';
  tag?: string;
  category?: string;
  platform?: string;
  status?: string;
  search?: string;
  sort?: 'name' | 'modified';
}

/** Normalizes text for accent- and case-insensitive matching. */
export function normalizeText(text: string): string {
  return text
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .toLowerCase();
}

export function searchableText(entry: RegistryEntry): string {
  return normalizeText(
    [
      entry.name,
      entry.slug,
      entry.id,
      entry.description,
      entry.category,
      entry.template ?? '',
      entry.platform,
      ...entry.tags,
      entry.catalog?.category ?? '',
      entry.catalog?.productType ?? '',
      ...(entry.catalog?.features ?? []),
    ].join(' ')
  );
}

/** Every whitespace-separated term must appear somewhere in the entry. */
export function filterEntries(
  entries: readonly RegistryEntry[],
  query: RegistryQuery
): RegistryEntry[] {
  const terms = query.search ? normalizeText(query.search).split(/\s+/).filter(Boolean) : [];
  const tag = query.tag?.toLowerCase();
  const out = entries.filter((entry) => {
    if (query.kind && query.kind !== 'all' && entry.kind !== query.kind) return false;
    if (tag && !entry.tags.some((t) => t.toLowerCase() === tag)) return false;
    if (query.category && entry.category !== query.category) return false;
    if (query.platform && entry.platform !== query.platform) return false;
    if (query.status && entry.status !== query.status) return false;
    if (terms.length > 0) {
      const text = searchableText(entry);
      if (!terms.every((term) => text.includes(term))) return false;
    }
    return true;
  });
  if (query.sort === 'modified') {
    out.sort((a, b) => b.modifiedAt.localeCompare(a.modifiedAt) || compareEntries(a, b));
  } else {
    out.sort(compareEntries);
  }
  return out;
}

/**
 * Storage namespace used when a template is opened as a live demo
 * (`protoyard dev <template>` or the gallery control server). Keeps demo
 * IndexedDB data out of prototype namespaces and out of the template's own
 * authoring namespace. Kebab-case only (manifest namespace rules); the task
 * form `template-demo.<name>` maps to `template-demo-<name>`.
 */
export function templateDemoNamespace(templateSlug: string): string {
  return `template-demo-${templateSlug}`;
}

export function findEntry(
  registry: Registry,
  slug: string,
  kind: FolderKind | 'any' = 'prototype'
): RegistryEntry | undefined {
  return registry.entries.find((e) => e.slug === slug && (kind === 'any' || e.kind === kind));
}
