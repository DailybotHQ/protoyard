import { cleanup, fireEvent, render, screen } from '@testing-library/svelte';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { mountPrototype } from '../src/index.ts';
import { SHELL_CSS_MARKER } from '../src/shell/frames/registry.ts';
import StaleWorldNotice, { type StaleWorldInfo } from '../src/shell/StaleWorldNotice.svelte';
import { createFakeRuntime } from './fixtures/fake-runtime.ts';
import ProbeApp from './fixtures/ProbeApp.svelte';

/**
 * When ensureSeeded() rebuilt a world made by other generator versions, the
 * renderer says so and offers the safety snapshot back; normal boots show
 * nothing and never load the notice.
 */

const reseeded: StaleWorldInfo = {
  scenario: 'empty',
  seed: 1,
  status: 'reseeded',
  snapshotId: 'snap_safety',
  reason: 'This data was generated by older generators.',
};

function withStale(stale: StaleWorldInfo | null) {
  const runtime = createFakeRuntime();
  Object.assign(runtime.scenarios, { staleWorld: () => stale });
  return runtime;
}

const notice = () => screen.queryByRole('region', { name: /Prototype data (rebuilt|kept)/ });

describe('stale world notice (mountPrototype)', () => {
  let destroy: (() => Promise<void>) | undefined;
  beforeEach(() => {
    document.documentElement.style.setProperty(SHELL_CSS_MARKER, '1');
  });
  afterEach(async () => {
    await destroy?.();
    destroy = undefined;
    document.body.replaceChildren();
    document.documentElement.removeAttribute('style');
    localStorage.clear();
  });

  async function boot(runtime: ReturnType<typeof createFakeRuntime>) {
    const target = document.body.appendChild(document.createElement('div'));
    const mounted = await mountPrototype({
      definition: runtime.definition,
      App: ProbeApp,
      target,
      search: '',
      devtools: false,
      createRuntime: () => runtime,
    });
    destroy = mounted.destroy;
  }

  it('shows nothing on a normal boot (staleWorld() is null, or absent)', async () => {
    await boot(withStale(null));
    await new Promise((r) => setTimeout(r, 20));
    expect(notice()).toBeNull();
    await destroy?.();
    destroy = undefined;
    document.body.replaceChildren();
    await boot(createFakeRuntime());
    await new Promise((r) => setTimeout(r, 20));
    expect(notice()).toBeNull();
  });

  it('explains a rebuilt world and restores the safety snapshot', async () => {
    const runtime = withStale(reseeded);
    const restore = vi.spyOn(runtime.snapshots, 'restore').mockResolvedValue();
    await boot(runtime);
    const region = await screen.findByRole('region', { name: 'Prototype data rebuilt' });
    expect(region.textContent).toContain('generator changed');
    expect(region.textContent).toContain('“Before refreshing Empty”');
    // DevTools is off in this boot, so the notice does not point at it.
    expect(region.textContent).not.toContain('DevTools');
    await fireEvent.click(screen.getByRole('button', { name: 'Restore previous data' }));
    expect(restore).toHaveBeenCalledWith('snap_safety');
    expect(await screen.findByText(/Your previous data is back/)).toBeTruthy();
    expect(screen.queryByRole('button', { name: 'Restore previous data' })).toBeNull();
  });
});

describe('StaleWorldNotice', () => {
  afterEach(() => cleanup());

  it('names the DevTools Snaps tab when DevTools is mounted, and dismisses', async () => {
    render(StaleWorldNotice, { runtime: createFakeRuntime(), stale: reseeded, devtools: true });
    expect(notice()?.textContent).toContain('DevTools → Snaps (Ctrl or ⌘ + .)');
    await fireEvent.click(screen.getByRole('button', { name: 'Dismiss' }));
    expect(notice()).toBeNull();
  });

  it('reports a restore failure instead of claiming success', async () => {
    const runtime = createFakeRuntime();
    vi.spyOn(runtime.snapshots, 'restore').mockRejectedValue(new Error('Snapshot not found.'));
    render(StaleWorldNotice, { runtime, stale: reseeded });
    await fireEvent.click(screen.getByRole('button', { name: 'Restore previous data' }));
    expect((await screen.findByRole('alert')).textContent).toContain('Snapshot not found.');
    expect(screen.queryByText(/Your previous data is back/)).toBeNull();
  });

  it('offers no restore when the data was kept or a sandbox had no snapshot', () => {
    const runtime = createFakeRuntime();
    render(StaleWorldNotice, {
      runtime,
      stale: { scenario: 'empty', seed: 1, status: 'kept', reason: 'kept' },
    });
    expect(notice()?.getAttribute('aria-label')).toBe('Prototype data kept');
    expect(notice()?.textContent).toContain('Reset the Empty scenario');
    expect(screen.queryByRole('button', { name: 'Restore previous data' })).toBeNull();
    cleanup();
    render(StaleWorldNotice, {
      runtime,
      stale: { scenario: 'empty', seed: 1, status: 'reseeded', reason: 'sandbox' },
    });
    expect(notice()?.textContent).toContain('no snapshot was saved');
    expect(screen.queryByRole('button', { name: 'Restore previous data' })).toBeNull();
  });
});
