// @vitest-environment node
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import * as root from '../src/index.ts';
import * as layouts from '../src/layouts/index.ts';
import * as patch from '../src/patch/index.ts';
import * as quality from '../src/quality/index.ts';
import * as schema from '../src/schema/index.ts';
import * as style from '../src/style/index.ts';
import * as text from '../src/text/index.ts';

/*
 * The deck READMEs hold three generated regions, so they cannot drift from the
 * code: the layout catalog table and the schema limits table
 * (packages/decks/README.md) and the keyboard table
 * (packages/decks-ui/README.md). The test also checks that every runtime
 * export of every @protoyard/decks subpath is named in the README.
 *
 * After changing the catalog, limits or key bindings, regenerate with
 *   PROTOYARD_UPDATE_README=1 pnpm vitest run packages/decks/tests/readme-sync.test.ts
 */

const DECKS_README = join(import.meta.dirname, '../README.md');
const DECKS_UI_README = join(import.meta.dirname, '../../decks-ui/README.md');
const UPDATE = process.env.PROTOYARD_UPDATE_README === '1';

const cell = (value: string) => value.replaceAll('|', '\\|').replaceAll('\n', ' ');

export function layoutCatalogTable(): string {
  const rows = layouts.DECK_LAYOUTS.map((layout) =>
    [
      `\`${layout.id}\``,
      cell(layout.label),
      layout.pacing.join(', '),
      cell(layout.limits.summary.join('; ')),
      cell(layout.useWhen[0] ?? ''),
    ].join(' | ')
  );
  return [
    '| Layout | Name | Pacing | Limits | Use when |',
    '| --- | --- | --- | --- | --- |',
    ...rows.map((row) => `| ${row} |`),
  ].join('\n');
}

/** What each `DECK_LIMITS` key bounds. A new key without a label fails the test. */
const LIMIT_LABELS: Record<keyof typeof schema.DECK_LIMITS, string> = {
  slides: 'Slides per deck',
  sections: 'Outline sections',
  sectionSlides: 'Slide ids per outline section',
  slideTitle: 'Slide title characters',
  slideNotes: 'Speaker notes characters per slide',
  sectionTitle: 'Section and outline title characters',
  stepLabel: 'Characters per step label',
  steps: 'Step labels per slide (and steps played separately)',
  propsKeys: 'Keys per catalog props object',
  propsArray: 'Items per catalog props array',
  propsDepth: 'Nesting depth of catalog props',
  propsString: 'Characters per catalog props string',
  freeBlocks: 'Blocks per free slide',
};

export function limitsTable(): string {
  const rows = Object.entries(schema.DECK_LIMITS).map(([key, value]) => {
    const label = LIMIT_LABELS[key as keyof typeof LIMIT_LABELS];
    if (!label) throw new Error(`DECK_LIMITS.${key} needs a label in readme-sync.test.ts`);
    return `| \`${key}\` | ${label} | ${value.toLocaleString('en-US')} |`;
  });
  return ['| `DECK_LIMITS` key | Bounds | Limit |', '| --- | --- | ---: |', ...rows].join('\n');
}

export function keyBindingsTable(): string {
  const rows = root.DECK_KEY_BINDINGS.map(
    (binding) =>
      `| ${binding.keys.map((key) => `\`${cell(key)}\``).join(', ')} | \`${binding.action}\` | ${cell(binding.label)} |`
  );
  return ['| Keys | Action | What it does |', '| --- | --- | --- |', ...rows].join('\n');
}

/** Reads (or, with PROTOYARD_UPDATE_README=1, rewrites) a generated region. */
function region(file: string, name: string, expected: string): string {
  const start = `<!-- ${name}:start (generated by packages/decks/tests/readme-sync.test.ts) -->`;
  const end = `<!-- ${name}:end -->`;
  const content = readFileSync(file, 'utf8');
  const from = content.indexOf(start);
  const to = content.indexOf(end);
  expect(from, `${file} is missing the ${name} start marker`).toBeGreaterThanOrEqual(0);
  expect(to, `${file} is missing the ${name} end marker`).toBeGreaterThan(from);
  const current = content.slice(from + start.length, to).trim();
  if (UPDATE && current !== expected) {
    writeFileSync(
      file,
      `${content.slice(0, from + start.length)}\n${expected}\n${content.slice(to)}`
    );
    return expected;
  }
  return current;
}

describe('deck READMEs stay in sync with the code', () => {
  it('lists every catalog layout, generated from DECK_LAYOUTS (AC)', () => {
    const table = layoutCatalogTable();
    expect(region(DECKS_README, 'layout-catalog', table)).toBe(table);
    for (const layout of layouts.DECK_LAYOUTS) expect(table).toContain(`\`${layout.id}\``);
    expect(layouts.DECK_LAYOUTS).toHaveLength(21);
  });

  it('states the schema limits from DECK_LIMITS', () => {
    const table = limitsTable();
    expect(region(DECKS_README, 'deck-limits', table)).toBe(table);
  });

  it('lists the keyboard shortcuts from DECK_KEY_BINDINGS in the decks-ui README', () => {
    const table = keyBindingsTable();
    expect(region(DECKS_UI_README, 'key-bindings', table)).toBe(table);
  });

  it('names every runtime export of every subpath', () => {
    const readme = readFileSync(DECKS_README, 'utf8');
    const subpaths = { '.': root, schema, layouts, style, quality, text, patch };
    const missing: string[] = [];
    for (const [subpath, module] of Object.entries(subpaths)) {
      for (const name of Object.keys(module)) {
        // Named inside a code span, possibly with a call or a type (`slideSteps(slide)`).
        if (!new RegExp(`\`[^\`]*\\b${name}\\b[^\`]*\``).test(readme)) {
          missing.push(`${subpath}: ${name}`);
        }
      }
    }
    expect(missing).toEqual([]);
  });

  it('keeps the package.json subpaths and the README exports table aligned', () => {
    const manifest = JSON.parse(
      readFileSync(join(import.meta.dirname, '../package.json'), 'utf8')
    ) as {
      exports: Record<string, string>;
    };
    const readme = readFileSync(DECKS_README, 'utf8');
    for (const subpath of Object.keys(manifest.exports)) {
      const name = subpath === '.' ? '@protoyard/decks' : `@protoyard/decks/${subpath.slice(2)}`;
      expect(readme, name).toContain(`| \`${name}\` |`);
    }
  });
});
